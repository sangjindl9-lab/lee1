const lang = (navigator.language || 'ko').toLowerCase();
const dict = lang.startsWith('ko') ? null : lang.startsWith('ja') ? JA : EN;
export const LANG = dict === null ? 'ko' : dict === JA ? 'ja' : 'en';

export function t(ko, params) {
  let s = (dict && dict[ko]) || ko;
  if (params) for (const k in params) s = s.split(`{${k}}`).join(params[k]);
  return s;
}

/** index.html 의 고정 문구를 바꾼다(data-i18n 속성 또는 아래 목록). */
export function applyStatic() {
  document.documentElement.lang = LANG;
  document.title = t('이음뷰어');
  for (const e of document.querySelectorAll('[data-i18n]')) e.textContent = t(e.dataset.i18n);
  for (const e of document.querySelectorAll('[data-i18n-html]')) e.innerHTML = e.dataset.i18nHtml.split('|').map(t).join('<br>');
  for (const e of document.querySelectorAll('[data-i18n-label]')) e.setAttribute('aria-label', t(e.dataset.i18nLabel));
}
